# Regenerates scripts/kind/seed/openzaak/00-restore-migrated-database.sql, the pre-migrated Open Zaak database that
# the Postgres of the kind stack restores before the seed data. With that dump in place, Open Zaak finds no database
# migrations left to apply when it starts.
#
# Run this script after a change of the Open Zaak image in scripts/kind/charts/zac-dev/values.yaml and commit the
# result. It starts Open Zaak on an empty database in temporary Docker containers, with the images of the kind stack,
# and removes them again afterwards.
#
# Environment:
#   DOCKER_USE_ARM64_CONTAINERS  'true' or 'false' to use the arm64 images of scripts/kind/values/arm64.yaml or not
#                                (default: 'true' on an arm64 host)
set -euo pipefail

KIND_DIR=$(cd "$(dirname "$0")" && pwd)
DUMP_FILE=$KIND_DIR/seed/openzaak/00-restore-migrated-database.sql
NAME=zac-openzaak-dump-$$
TIMEOUT_SECONDS=600

fail() { printf '\n\033[1;31m%s\033[0m\n' "$*" >&2; exit 1; }

values_files=("$KIND_DIR/charts/zac-dev/values.yaml")
use_arm64=${DOCKER_USE_ARM64_CONTAINERS:-}
if [ -z "$use_arm64" ]; then
  case $(uname -m) in arm64 | aarch64) use_arm64=true ;; *) use_arm64=false ;; esac
fi
if [ "$use_arm64" != false ] && [ "$use_arm64" != 0 ]; then
  echo "Using the arm64 images of scripts/kind/values/arm64.yaml"
  values_files+=("$KIND_DIR/values/arm64.yaml")
fi

image() {
  python3 - "$1" "${values_files[@]}" << 'PY'
import re, sys
image = None
for values_file in sys.argv[2:]:
    match = re.search(rf"^{sys.argv[1]}:\n  image: (\S+)$", open(values_file).read(), re.M)
    image = match.group(1) if match else image
if not image:
    sys.exit(f"No image for '{sys.argv[1]}' in {', '.join(sys.argv[2:])}")
print(image)
PY
}
openzaak_image=$(image openzaak)
postgres_image=$(image postgres)
redis_image=$(image redis)

cleanup() {
  echo "Removing the temporary containers ..."
  docker rm --force "$NAME-openzaak" "$NAME-postgres" "$NAME-redis" > /dev/null 2>&1 || true
  docker network rm "$NAME" > /dev/null 2>&1 || true
}
trap cleanup EXIT

wait_for() {
  local description=$1 container=$2
  shift 2
  local deadline=$(($(date +%s) + TIMEOUT_SECONDS))
  until "$@" > /dev/null 2>&1; do
    [ "$(docker inspect --format '{{.State.Running}}' "$container")" = true ] ||
      fail "$description stopped: $(docker logs --tail 50 "$container" 2>&1)"
    [ "$(date +%s)" -lt "$deadline" ] || fail "$description did not start within $TIMEOUT_SECONDS seconds"
    sleep 2
  done
}

docker network create "$NAME" > /dev/null
docker run --detach --name "$NAME-redis" --network "$NAME" --network-alias redis "$redis_image" > /dev/null
docker run --detach --name "$NAME-postgres" --network "$NAME" --network-alias postgres \
  --env POSTGRES_PASSWORD=postgres "$postgres_image" > /dev/null
# the entrypoint of Postgres initializes the database with a server that only listens on its socket
wait_for "Postgres" "$NAME-postgres" docker exec "$NAME-postgres" pg_isready --host 127.0.0.1 --username postgres
# the same role and database as the postgres-initdb ConfigMap of charts/zac-dev creates, without the PostGIS
# extensions that the entrypoint of the PostGIS image adds to the database of POSTGRES_DB
docker exec "$NAME-postgres" psql --username postgres --quiet --set ON_ERROR_STOP=1 \
  --command "CREATE ROLE openzaak LOGIN SUPERUSER PASSWORD 'openzaak'" \
  --command "CREATE DATABASE openzaak OWNER openzaak" > /dev/null

echo "Starting $openzaak_image on an empty database and waiting until it has applied its migrations ..."
docker run --detach --name "$NAME-openzaak" --network "$NAME" \
  --env DB_HOST=postgres --env DB_NAME=openzaak --env DB_USER=openzaak --env DB_PASSWORD=openzaak \
  --env CACHE_DEFAULT=redis:6379/0 --env CACHE_AXES=redis:6379/0 \
  --env CELERY_BROKER_URL=redis://redis:6379/1 --env CELERY_RESULT_BACKEND=redis://redis:6379/1 \
  --env ALLOWED_HOSTS='*' --env SECRET_KEY=regenerate-openzaak-database-dump \
  --env DJANGO_SETTINGS_MODULE=openzaak.conf.docker --env DISABLE_2FA=true --env NOTIFICATIONS_DISABLED=true \
  --env OTEL_SDK_DISABLED=true --env OPENZAAK_SUPERUSER_USERNAME=admin \
  --env OPENZAAK_SUPERUSER_EMAIL=noreply@example.com --env DJANGO_SUPERUSER_PASSWORD=admin \
  "$openzaak_image" > /dev/null
wait_for "Open Zaak" "$NAME-openzaak" docker exec "$NAME-openzaak" python -c "import requests
exit(requests.head('http://localhost:8000/admin/').status_code not in [200, 302])"

echo "Writing $DUMP_FILE ..."
{
  echo "-- Open Zaak database schema and initial data as created by $openzaak_image on its first start."
  echo "-- Generated by $(basename "$0") on $(date -u +%Y-%m-%d). Do not edit by hand; rerun that script instead."
  docker exec "$NAME-postgres" pg_dump --username openzaak --dbname openzaak --no-owner --no-privileges
} > "$DUMP_FILE.tmp"
mv "$DUMP_FILE.tmp" "$DUMP_FILE"

echo "Done. Dump size: $(wc -c < "$DUMP_FILE" | tr -d ' ') bytes"
